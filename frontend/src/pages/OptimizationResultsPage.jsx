import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { 
  Zap, 
  FileText, 
  ShieldCheck, 
  Sparkles, 
  CheckCircle2, 
  XCircle, 
  Layers,
  ArrowRight
} from 'lucide-react';
import PageContainer from '../components/layout/PageContainer';
import PageHeader from '../components/layout/PageHeader';
import OptimizationSummary from '../components/optimization/OptimizationSummary';
import ProjectResultsList from '../components/optimization/ProjectResultsList';
import ConstraintInspector from '../components/optimization/ConstraintInspector';
import { useScenario } from '../context/ScenarioContext';
import Button from '../components/ui/Button';
import Card from '../components/ui/Card';
import { EmptyState } from '../components/ui/States';

export default function OptimizationResultsPage() {
  const navigate = useNavigate();
  const { 
    lastResult, 
    projects, 
    runOptimization, 
    isOptimizing, 
    isIllustrativeActive, 
    toggleIllustrative,
    backendStatus 
  } = useScenario();

  // Active Tab
  const [activeTab, setActiveTab] = useState('summary'); // 'summary' | 'funded' | 'unfunded' | 'constraints'

  const handleRunOptimization = async () => {
    try {
      await runOptimization();
    } catch {
      // Handled in context
    }
  };

  const fundedCount = lastResult?.funded_ids?.length || 0;
  const unfundedCount = lastResult?.unfunded_ids?.length || 0;

  return (
    <PageContainer>
      <PageHeader
        eyebrow="SOLVER OUTCOMES & DECISION PROOFS"
        title="Optimization"
        italicAccent="Results"
        description="Detailed solution breakdown generated by mathematical multi-criteria optimization, validating budget ceilings, accessibility quotas, and prerequisite constraints."
        actions={
          <div className="flex items-center space-x-2">
            {!backendStatus.connected && !lastResult && (
              <Button
                variant="secondary"
                size="sm"
                icon={Sparkles}
                onClick={() => toggleIllustrative(true)}
              >
                Load Sample Preview
              </Button>
            )}
            <Button
              variant="primary"
              size="sm"
              icon={Zap}
              isLoading={isOptimizing}
              onClick={handleRunOptimization}
            >
              {lastResult ? 'Rerun Solver' : 'Execute Optimization'}
            </Button>
          </div>
        }
      />

      {/* Main Content: If results exist, display tabbed view; otherwise EmptyState */}
      {lastResult ? (
        <div className="grid grid-cols-1 lg:grid-cols-4 gap-6">
          
          {/* Desktop Vertical Navigation Tabs / Mobile Horizontal Bar */}
          <div className="lg:col-span-1">
            <div className="sticky top-20 bg-surface rounded-panel border border-border-hairline p-2 space-y-1 shadow-subtle flex lg:flex-col overflow-x-auto lg:overflow-visible">
              <button
                type="button"
                onClick={() => setActiveTab('summary')}
                className={`w-full flex items-center justify-between px-3 py-2.5 rounded-lg text-xs font-sans uppercase tracking-wider font-semibold transition-colors shrink-0 lg:shrink ${
                  activeTab === 'summary'
                    ? 'bg-burgundy text-page shadow-sm'
                    : 'text-charcoal hover:bg-surface-alt'
                }`}
              >
                <span>Executive Summary</span>
                <Layers className="w-3.5 h-3.5 ml-2 hidden lg:inline" />
              </button>

              <button
                type="button"
                onClick={() => setActiveTab('funded')}
                className={`w-full flex items-center justify-between px-3 py-2.5 rounded-lg text-xs font-sans uppercase tracking-wider font-semibold transition-colors shrink-0 lg:shrink ${
                  activeTab === 'funded'
                    ? 'bg-burgundy text-page shadow-sm'
                    : 'text-charcoal hover:bg-surface-alt'
                }`}
              >
                <span>Funded Projects ({fundedCount})</span>
                <CheckCircle2 className="w-3.5 h-3.5 ml-2 hidden lg:inline" />
              </button>

              <button
                type="button"
                onClick={() => setActiveTab('unfunded')}
                className={`w-full flex items-center justify-between px-3 py-2.5 rounded-lg text-xs font-sans uppercase tracking-wider font-semibold transition-colors shrink-0 lg:shrink ${
                  activeTab === 'unfunded'
                    ? 'bg-burgundy text-page shadow-sm'
                    : 'text-charcoal hover:bg-surface-alt'
                }`}
              >
                <span>Unfunded ({unfundedCount})</span>
                <XCircle className="w-3.5 h-3.5 ml-2 hidden lg:inline" />
              </button>

              <button
                type="button"
                onClick={() => setActiveTab('constraints')}
                className={`w-full flex items-center justify-between px-3 py-2.5 rounded-lg text-xs font-sans uppercase tracking-wider font-semibold transition-colors shrink-0 lg:shrink ${
                  activeTab === 'constraints'
                    ? 'bg-burgundy text-page shadow-sm'
                    : 'text-charcoal hover:bg-surface-alt'
                }`}
              >
                <span>Constraint Inspector</span>
                <ShieldCheck className="w-3.5 h-3.5 ml-2 hidden lg:inline" />
              </button>
            </div>
          </div>

          {/* Active Tab Panel Content */}
          <div className="lg:col-span-3">
            {activeTab === 'summary' && (
              <OptimizationSummary result={lastResult} />
            )}

            {activeTab === 'funded' && (
              <Card>
                <ProjectResultsList
                  filter="funded"
                  result={lastResult}
                  allProjects={projects}
                />
              </Card>
            )}

            {activeTab === 'unfunded' && (
              <Card>
                <ProjectResultsList
                  filter="unfunded"
                  result={lastResult}
                  allProjects={projects}
                />
              </Card>
            )}

            {activeTab === 'constraints' && (
              <Card>
                <ConstraintInspector
                  result={lastResult}
                  allProjects={projects}
                />
              </Card>
            )}
          </div>

        </div>
      ) : (
        <EmptyState
          title="Optimization Has Not Been Executed"
          description="The mathematical optimization engine has not solved an allocation for the active scenario. Run the solver or activate the illustrative preview to review sample outputs."
          actionLabel="Execute Optimization"
          onAction={handleRunOptimization}
        />
      )}
    </PageContainer>
  );
}

